'use strict';
const assert=require('node:assert/strict');
const S=require('../src/spire-ascent.js');
assert.equal(S.FLOOR2,'windspire2');
assert.equal(S.FLOOR3,'windspire3');
assert.equal(S.GUARD_KEY,'windspire/星風の番人 カイト');
assert.equal(S.FINAL_KEY,'windspire3/天空の試練官 セイ');
assert.deepEqual(S.TARGET,[1,0,3]);
const state={defeated:{},events:{}};
const initial=JSON.stringify(state);
assert.equal(S.canEnter(state,S.FLOOR2),false,'First-floor guardian gates 2F');
assert.equal(S.canEnter(state,S.FLOOR3),false,'Third floor remains sealed');
assert.equal(S.claim(state).ok,false);
assert.equal(S.status(state).phase,'guardian');
const defeated={defeated:{[S.GUARD_KEY]:true},events:{}};
assert.equal(S.canEnter(defeated,S.FLOOR2),true);
assert.equal(S.canEnter(defeated,S.FLOOR3),false);
assert.equal(S.guardianPassed({events:{regionalExpeditions:{windspire:{claimed:true}}}}),true,'Old save with 1F prize permits ascent');
assert.equal(S.rotate({},6,1).ok,false);
assert.equal(S.rotate({},0,2.4).ok,false);
assert.deepEqual(S.normalize({}).vanes,[2,2,2]);
assert.equal(S.rotate({},0,-1).progress.vanes[0],1,'Counterclockwise adjusts east vane to east');
const wrong=S.rotate({},2,1);
assert.equal(wrong.kind,'rotated');
assert.equal(S.snapshot({spireAscent:wrong.progress}).complete,false);
let saved={};
for(const [i,delta] of [[0,-1],[1,2],[2,1]]){
 const r=S.rotate(saved,i,delta);
 assert.equal(r.ok,true);
 saved={spireAscent:r.progress};
}
assert.equal(JSON.stringify(state),initial,'Puzzle never mutates original save');
assert.deepEqual(saved.spireAscent.vanes,[1,0,3]);
assert.equal(S.snapshot(saved).aligned,3);
assert.equal(S.snapshot(saved).complete,true);
assert.equal(S.rotate(saved,0,1).kind,'done','Once aligned vanes stay fixed');
assert.equal(S.canEnter({...defeated,events:saved},S.FLOOR3),true);
const tiles=Array.from({length:13},()=>Array.from({length:16},()=>1));
S.prepare(S.FLOOR2,tiles,{});
assert(Array.from({length:14},(_,i)=>tiles[6][i+1]).every(v=>v===3),'Before solve, a continuous wind chasm blocks north');
assert.equal(tiles[3][8],5,'Third-floor stair is solid while unsolved');
S.prepare(S.FLOOR2,tiles,saved);
assert.deepEqual(tiles[6].slice(7,10),[13,13,13],'Three aligned vanes materialize real three-tile walkway');
assert.equal(tiles[6][6],3,'Other unbridged cells remain impassable');
assert.equal(tiles[3][8],6,'Third-floor stair actually opens');
assert.equal(S.prepare('windspire',tiles,saved),false);
assert(S.clue().includes('東の風'));
const wardenWon={...defeated,events:saved,defeated:{...defeated.defeated,[S.FINAL_KEY]:true}};
assert.equal(S.status(wardenWon).phase,'treasure');
const gift=S.claim(wardenWon);
assert.equal(gift.ok,true);
assert.equal(gift.reward.bag.ether,3);
assert.equal(gift.reward.bag.orb,5);
assert.equal(gift.reward.bag.speedCharm,1);
assert.equal(gift.reward.money,750);
const reload={...wardenWon,events:{spireAscent:gift.progress}};
assert.equal(S.claim(reload).ok,false,'One-time summit reward survives reload');
assert.equal(S.status(reload).phase,'complete');
assert.equal(S.normalize({spireAscent:{vanes:[-1,5,8],bridge:true,claimed:true}}).vanes[0],3,'Malformed or old save data wraps safely');
console.log('PASS: 3F Skywind Spire: guardian gate, wind vanes, solid bridge, summit guard and exactly-once reward');
