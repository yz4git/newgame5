'use strict';
const assert=require('node:assert/strict');
const W=require('../src/town-workshop.js');
assert.equal(W.RECIPES.length,5);
assert.equal(W.townTier({story:{stage:3}}),0,'Opening sequence never unlocks construction');
const base={story:{stage:12},bag:{orb:4,potion:4,herb:2,ether:3,powerCharm:0,guardCharm:0,speedCharm:0},money:520,events:{fieldRequests:{}}};
assert.equal(W.townTier(base),0);
assert.equal(W.available(base).length,0);
assert.equal(W.canCraft('restore',base).ok,false);
const claims=id=>({accepted:true,claimed:true,choice:'supply'});
base.events.fieldRequests.flower=claims('flower');
assert.equal(W.townTier(base),1);
base.events.fieldRequests.forest=claims('forest');
assert.equal(W.townTier(base),2);
assert.deepEqual(W.available(base).map(r=>r.id),['restore','medicine']);
assert.equal(W.canCraft('power',base).ok,false);
const one=W.craft('restore',base);
assert(one.ok);
assert.equal(one.bag.orb,3);
assert.equal(one.bag.potion,3);
assert.equal(one.bag.ether,4);
assert.equal(base.bag.orb,4,'Pure craft must not mutate save input');
assert.equal(base.money,520);
assert.equal(one.money,520);
const two=W.craft('medicine',base);
assert(two.ok);
assert.equal(two.bag.potion,2);
assert.equal(two.bag.herb,3);
base.events.fieldRequests.lake=claims('lake');
assert.equal(W.townTier(base),3);
assert.equal(W.canCraft('power',base).ok,true);
let r=W.craft('power',base);
assert.equal(r.bag.powerCharm,1);
assert.equal(r.bag.orb,2);
assert.equal(r.money,470);
const moneyless={...base,money:1};
assert.equal(W.canCraft('power',moneyless).ok,false);
const insufficient={...base,bag:{...base.bag,orb:0}};
assert.equal(W.canCraft('restore',insufficient).ok,false);
assert.equal(W.craft('restore',insufficient).bag,null);
assert.equal(W.canCraft('not-a-recipe',base).ok,false);
assert.equal(W.recipeText(W.RECIPES[0]).includes('星玉×1'),true);
base.events.fieldRequests.highland=claims('highland');
assert.equal(W.townTier(base),4);
assert.equal(W.available(base).length,4);
assert.equal(W.archiveUnlocked(base),false,'Festival must be completed to enter archive');
assert.equal(W.readPanel('forest',base).ok,false);
assert.equal(W.archiveReward(base).ok,false);
base.events.townLegacy={accepted:true,claimed:true};
assert.equal(W.townTier(base),5);
assert.equal(W.available(base).length,5);
assert.equal(W.archiveUnlocked(base),true);
let state=W.archiveState(base);
assert.equal(Object.values(state.panels).filter(Boolean).length,0);
assert.equal(W.archiveReward(base).ok,false,'Unvisited archive cannot be looted');
for(const panel of W.PANELS){
 const result=W.readPanel(panel,base);
 assert.equal(result.ok,true);
 base.events.townWorkshop={archive:result.state};
}
assert.equal(W.readPanel('bogus',base).ok,false);
const completion=W.archiveReward(base);
assert.equal(completion.ok,true);
assert.equal(completion.reward.money,300);
assert.equal(completion.reward.bag.powerCharm,1);
assert.equal(completion.reward.bag.ether,3);
base.events.townWorkshop={archive:completion.state};
assert.equal(W.archiveReward(base).ok,false,'Collected archive cache never duplicates');
const roundtrip=JSON.parse(JSON.stringify(base));
assert.equal(W.archiveReward(roundtrip).ok,false,'Collected cache survives JSON serialization');
assert.equal(Object.values(W.archiveState(roundtrip).panels).filter(Boolean).length,3);
console.log('PASS: town-gated workshop, recipe costs, pure inventory conversion, archive proof and persistent one-time reward');
