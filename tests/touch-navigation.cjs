'use strict';
const assert=require('node:assert/strict');
const N=require('../src/touch-navigation.js');
const pad={left:0,top:0,width:128,height:96};
assert.equal(N.direction(64,48,pad),null,'Touch center is a no-move deadzone');
assert.equal(N.direction(64,8,pad),'up');
assert.equal(N.direction(64,90,pad),'down');
assert.equal(N.direction(8,48,pad),'left');
assert.equal(N.direction(122,48,pad),'right');
assert.equal(N.direction(122,3,pad),'up','Direction favors the larger normalized axis');
assert.equal(N.direction(64,0,null),null);
const cells=[{disabled:false},{disabled:false},{disabled:true},{disabled:false},{disabled:false},{disabled:false},{disabled:false}];
assert.equal(N.first(cells),0);
assert.equal(N.next(cells,0,'right'),1);
assert.equal(N.next(cells,0,'down'),4,'Skip disabled row and reach next open item in the same column');
assert.equal(N.next(cells,1,'down'),3);
assert.equal(N.next(cells,5,'left'),4);
assert.equal(N.next(cells,6,'up'),4);
assert.equal(N.next(cells,0,'up'),0,'At edge the focus remains in place');
assert.equal(N.next(cells,1,'invalid'),1);
assert.equal(N.next([{disabled:true},{disabled:true}],0,'down'),-1);
assert.equal(N.next([{disabled:true},{disabled:false}],0,'left'),1);
console.log('PASS: slide-to-turn directional geometry, disabled-aware menu navigation, edges and active focus');
