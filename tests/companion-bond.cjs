'use strict';
const assert=require('node:assert/strict');
const C=require('../src/companion-bond.js');
const save={steps:0,map:'forest',events:{},party:[{id:'chiro',hp:30,maxHp:30,friendship:70,status:''}],companionName:'チロップ'};
assert.equal(C.visit('talk',{party:[]}).ok,false);
assert.equal(C.visit('unknown',save).ok,false);
const greet=C.visit('talk',save);
assert.match(greet.text,/木の葉|森/);
assert.equal(greet.bond,0);
let pet=C.visit('pet',save);
assert.equal(pet.friendship,72);
save.party[0].friendship=pet.friendship;save.events.companion=pet.progress;
pet=C.visit('pet',save);
assert.equal(pet.bond,0,'Petting immediately again never farms friendship');
save.steps=40;
pet=C.visit('pet',save);
assert.equal(pet.bond,2);
save.events.companion=pet.progress;
save.steps=95;
let found=C.visit('search',save,()=>0.01);
assert.equal(found.ok,true);
assert.equal(found.reward.item,'herb');
assert.equal(found.reward.count,1);
assert.equal(found.bond,1);
save.events.companion=found.progress;
const repeat=C.visit('search',save,()=>0.01);
assert.equal(repeat.reward,null,'No back-to-back item farming');
save.steps=205;
const again=C.visit('search',save,()=>.99);
assert.equal(again.reward,null,'Search does not guarantee a find');
save.party[0].status='どく';
assert.match(C.visit('talk',save).text,/手当て/);
save.party[0].status='';
save.party[0].hp=3;
assert.match(C.visit('talk',save).text,/休ませ/);
assert.equal(C.status({friendship:220}),'すっかり心を通わせている');
assert.equal(C.normalize(null).lastPetStep,-40);
console.log('PASS: follower dialogues, friendship cooldown, weathered terrain text and limited treasures');
