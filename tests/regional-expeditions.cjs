'use strict';
const assert=require('node:assert/strict');
const E=require('../src/regional-expeditions.js');
const rooms=['forestgrotto','tidevault','windspire'];
assert.equal(Object.keys(E.ROOMS).length,3);
assert.deepEqual(E.FOREST_ORDER,['sprout','rain','moon']);
assert.deepEqual(E.LAKE_TARGET,[true,false,true]);
const original={},snapshot=JSON.stringify(original);
let s=E.normalize(original);
assert.equal(s.forestgrotto.step,0);
assert.equal(s.tidevault.valves[1],true);
assert.deepEqual(s.tidevault.valves,[false,true,false]);
assert.equal(E.claim(original,'windspire',false).ok,false,'Cannot steal guardian reward');
assert.equal(E.claim(original,'unknown').ok,false);
assert.equal(E.press(original,'missing').ok,false);
assert.equal(E.toggle(original,3).ok,false);
assert.equal(E.press(original,'moon').kind,'reset','Wrong first rune resets progress');
let a=E.press(original,'sprout');
assert.equal(a.kind,'progress');
assert.equal(a.progress.forestgrotto.step,1);
assert.equal(JSON.stringify(original),snapshot,'Transitions cannot mutate raw saves');
let b=E.press({regionalExpeditions:a.progress},'moon');
assert.equal(b.progress.forestgrotto.step,0,'Unexpected rune resets the series');
let events={};
for(const item of ['sprout','rain','moon']){
 const x=E.press(events,item);assert.equal(x.ok,true);
 events={regionalExpeditions:x.progress};
}
assert(E.state(events,'forestgrotto').ready);
assert.equal(E.press(events,'rain').kind,'done','Completed rune stones are stable');
const gift=E.claim(events,'forestgrotto');
assert(gift.ok);assert.equal(gift.reward.bag.herb,2);
events={regionalExpeditions:gift.progress};
assert.equal(E.claim(events,'forestgrotto').ok,false,'One-time cave cache cannot duplicate');
const fresh=E.normalize({});
const locked=Array.from({length:13},()=>Array.from({length:16},()=>1));
E.prepare('tidevault',locked,{});
assert(Array.from({length:14},(_,i)=>locked[6][i+1]).every(t=>t===3),'Unsolved sluice has uninterrupted impassable water');
let tide={};
for(const valve of [0,1,2]){
 const x=E.toggle(tide,valve);assert(x.ok);
 tide={regionalExpeditions:x.progress};
}
assert(E.state(tide,'tidevault').solved);
E.prepare('tidevault',locked,tide);
assert([7,8,9].every(x=>locked[6][x]===13),'Bridge only appears after balancing three sluices');
assert.equal(locked[6][6],3);
assert.equal(E.toggle(tide,1).kind,'done','Completed valve state cannot be broken');
const tidal=E.claim(tide,'tidevault');
assert(tidal.ok);assert.equal(tidal.reward.bag.orb,4);
assert.equal(tidal.reward.money,280);
assert.equal(E.claim({regionalExpeditions:tidal.progress},'tidevault').ok,false);
const guardian=E.claim({},'windspire',true);
assert(guardian.ok);
assert.equal(guardian.reward.bag.guardCharm,1);
assert.equal(guardian.reward.bag.powerCharm,1);
assert.equal(guardian.reward.money,420);
assert.equal(E.claim({regionalExpeditions:guardian.progress},'windspire',true).ok,false);
assert.equal(E.claim({},'windspire',false).ok,false);
assert(E.clue('forestgrotto').includes('芽吹き'));
assert(E.clue('tidevault').includes('西と東'));
assert(E.clue('windspire').includes('守り手'));
for(const room of rooms)assert.equal(typeof E.ROOMS[room].name,'string');
assert.equal(E.prepare('forestgrotto',locked,{}),false);
assert.deepEqual(E.normalize({regionalExpeditions:gift.progress}).forestgrotto.claimed,true);
assert.equal(E.normalize({regionalExpeditions:{forestgrotto:{step:Infinity}}}).forestgrotto.step,0);
console.log('PASS: three replay-safe side quests, forest order, water bridge puzzle, guardian gate and exactly-once rewards');
