'use strict';
const assert=require('node:assert/strict');
const S=require('../src/story.js');
const s=S.fresh();
assert.equal(s.stage,0);
assert.equal(S.chapter(s).id,'awaken');
assert.equal(S.advance(s,2),false,'Cannot skip chapters');
assert.equal(S.advance(s,1),true);
assert.equal(S.advance(s,1),false,'Cannot repeat stage');
assert.equal(S.canWarp(s,'home','village').allowed,false);
assert.equal(S.advance(s,2),true);
assert.equal(S.canWarp(s,'home','village').allowed,true);
assert.equal(S.canWarp(s,'village','lab').allowed,true);
assert.equal(S.canWarp(s,'village','route').allowed,false);
assert.equal(S.advance(s,3),true);
assert.equal(S.canWarp(s,'lab','village').allowed,false);
assert.equal(S.advance(s,4),true);
assert.equal(S.canWarp(s,'lab','village').allowed,true);
assert.equal(S.advance(s,5),true);
assert.equal(S.advance(s,6),true);
assert.equal(S.canWarp(s,'village','route').allowed,true);
assert.equal(S.advance(s,7),true);
assert.equal(S.canWarp(s,'route','forest').allowed,false);
assert.equal(S.canWarp(s,'route','lake').allowed,true);
assert.equal(S.canWarp(s,'lake','observatory').allowed,true);
assert.equal(S.advance(s,8),true);
assert.equal(S.mustRivalBattle(s,'route','village',11,26),true);
assert.equal(S.mustRivalBattle(s,'route','village',11,13),false);
assert.equal(S.mustRivalBattle(s,'route','forest',11,26),false);
assert.equal(S.advance(s,9),true);
assert.equal(S.mustRivalBattle(s,'route','village',11,26),false,'Rival encounter only triggers once');
assert.equal(S.advance(s,10),true);
assert.equal(S.advance(s,11),true);
assert.equal(S.advance(s,12),true);
assert.equal(S.earlyTrainerEnabled(s),true);
assert.equal(S.canWarp(s,'route','forest').allowed,true);
assert.equal(S.advance(s,13),false);
assert.equal(S.rivalFor('flamio'),'aquill');
assert.equal(S.rivalFor('leafin'),'flamio');
assert.equal(S.rivalFor('aquill'),'leafin');
assert.equal(S.normalize(null).stage,12,'Old save begins in open world');
assert.equal(S.normalize({stage:8,playerName:'アキ',parcel:true}).stage,8);
assert.equal(S.startAt().id,'bedroom');
assert.equal(S.CHAPTERS.length,13);
console.log('PASS: opening chapter state machine, warp gates, early training locks, rival choice and old-save migration');
