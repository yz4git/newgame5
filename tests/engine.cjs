/* Automated unit tests for the original ASTRA RPG engine. */
'use strict';
const assert=require('node:assert/strict');
const E=require('../src/rpg-engine.js');
const species={
 flamio:{name:'ヒノコロ',type:'火',hp:29,atk:11,def:8,spd:11,moves:['ひっかく','ひのこ']},
 flaro:{name:'カグツバネ',type:'火',hp:44,atk:17,def:12,spd:15,moves:['ひっかく','ひのこ','ほのおのうず']},
 leafin:{name:'モコリーフ',type:'草',hp:34,atk:9,def:11,spd:8,moves:['たいあたり','はっぱカッター']}
};
const moves={...E.NEW_MOVES,'ひのこ':{p:48,type:'火'},'はっぱカッター':{p:47,type:'草'},'きあいだめ':{effect:'focus'}};
const stable=()=>0.5;
const fire=E.makeCreature('flamio',15,species,moves,stable);
const grass=E.makeCreature('leafin',15,species,moves,stable);
assert.equal(fire.level,15);
assert.ok(fire.iv.hp>=0&&fire.iv.hp<=31);
assert.equal(fire.moves.includes('ひのこ'),true);
assert.ok(fire.uid);
assert.ok(E.statsFor(fire,species.flamio).spd>0);
assert.ok(E.maxHpFor(species.flamio,fire.level,fire.iv)>species.flamio.hp);
const hpBefore=grass.hp;
const hit=E.calcDamage(fire,grass,'ひのこ',species,moves,(a,b)=>a==='火'&&b==='草'?1.5:1,stable);
assert.ok(hit.damage>0);
assert.equal(grass.hp,hpBefore-hit.damage);
assert.ok(hit.efficacy>1);
const missed=E.calcDamage(fire,grass,'ひのこ',species,moves,()=>1,()=>.99);
assert.equal(missed.damage,0);
fire.xp=0;
const level=E.gainXP(fire,E.xpNeed(15),species,moves,stable);
assert.ok(level.levels.includes(16));
assert.equal(fire.id,'flaro','starter evolves at level 16');
assert.equal(level.evolved.to,'flaro');
assert.ok(fire.moves.length<=4);
assert.ok(fire.hp<=fire.maxHp);
const illness=E.makeCreature('leafin',5,species,moves,stable);
illness.status='どく';const old=illness.hp;
const tick=E.afterTurn(illness);
assert.ok(tick.damage>0&&illness.hp<old);
const pr=E.catchProbability(illness,species);
illness.hp=1;illness.status='ねむり';
assert.ok(E.catchProbability(illness,species)>pr);
illness.statusTurns=2;assert.equal(E.skipStatus(illness,stable),'ねむり');
const encounter=E.chooseEncounter([['flamio',5],['leafin',7]],{rng:stable,phase:1});
assert.ok(encounter.id&&encounter.level>=5);
const boxes=E.emptyBoxes();
const party=[E.makeCreature('flamio',5,species,moves,stable)];
assert.equal(E.deposit(boxes,party,0).ok,false,'last creature protected');
party.push(E.makeCreature('leafin',6,species,moves,stable));
assert.equal(E.deposit(boxes,party,1).ok,true);
assert.equal(party.length,1);
assert.equal(boxes[0].members.length,1);
assert.equal(E.takeFromStorage(boxes,0,0,party).ok,true);
assert.equal(party.length,2);
const legacy={saveVersion:1,map:'village',party:[{id:'flamio',level:5,hp:9,maxHp:41,xp:2,moves:null}],boxes:null};
const migrated=E.migrateSave(legacy,species,moves,stable);
assert.equal(migrated.saveVersion,2);
assert.equal(migrated.party[0].hp,9,'legacy health is preserved');
assert.ok(migrated.party[0].iv&&migrated.party[0].pp);
assert.ok(Array.isArray(migrated.boxes));
const trainee=E.makeCreature('flamio',8,species,moves,stable);
const atk0=E.statsFor(trainee,species.flamio).atk;
trainee.heldItem='powerCharm';
const atk1=E.statsFor(trainee,species.flamio).atk;
assert.ok(atk1>=atk0,'Power charm does not reduce attack');
trainee.heldItem=null;
const evBefore=trainee.ev.atk;
E.gainEffort(trainee,fire,species);
assert.ok(trainee.ev.atk>=evBefore,'Effort system updated');
const scripted={events:{},bag:{orb:0},money:100,quest:'start'};
const story=[{op:'message',text:'研究開始'},{op:'item',id:'orb',count:3,unless:'firstGift'},{op:'flag',key:'firstGift'},{op:'quest',value:'field'},{op:'money',amount:50}];
E.applyEvent(story,scripted);
assert.equal(scripted.bag.orb,3);
assert.equal(scripted.money,150);
assert.equal(scripted.quest,'field');
E.applyEvent(story,scripted);
assert.equal(scripted.bag.orb,3,'Event item granted only once');
// The event VM supports persistent conditions, nested branches, choices and one-time outcomes.
const eventState={bag:{orb:1,ether:0},events:{},caught:{flamio:1,leafin:1,crag:1},defeated:{A:1,B:1},party:[fire],money:100,quest:'route',visited:{lake:true},badge:false};
assert.equal(E.eventCondition({all:[{caughtAtLeast:3},{notFlag:'claimed'},{visited:'lake'}]},eventState),true);
assert.equal(E.eventCondition({any:[{badge:true},{trainersAtLeast:2}]},eventState),true);
assert.equal(E.eventCondition({not:{badge:true}},eventState),true);
const optionScript=[
 {op:'branch',test:{caughtAtLeast:3},then:[
  {op:'message',text:'調査成功'},
  {op:'choice',options:[
   {text:'星玉',steps:[{op:'item',id:'orb',count:3},{op:'flag',key:'claimed'}]},
   {text:'PP回復',steps:[{op:'item',id:'ether',count:2},{op:'flag',key:'claimed'}]}
  ]}
 ],else:[{op:'message',text:'まだ足りない'}]}
];
const offer=E.runEvent(optionScript,eventState);
assert.equal(offer.messages[0],'調査成功');
assert.equal(offer.choices.length,2);
assert.equal(eventState.bag.orb,1,'Choice effects are deferred');
E.runEvent(offer.choices[1].steps,eventState);
assert.equal(eventState.bag.ether,2);
assert.equal(eventState.events.claimed,true);
E.runEvent([{op:'branch',test:{notFlag:'claimed'},then:[{op:'item',id:'orb',count:9}],else:[{op:'quest',value:'reward_claimed'}]}],eventState);
assert.equal(eventState.bag.orb,1,'Branch excludes already claimed reward');
assert.equal(eventState.quest,'reward_claimed');
E.runEvent([{op:'takeItem',id:'orb',count:10}],eventState);
assert.equal(eventState.bag.orb,1,'Unaffordable item transaction must not deduct');
const exhausted=E.makeCreature('flamio',5,species,moves,stable);
const recoilBefore=exhausted.hp;
const struggle=E.calcDamage(exhausted,E.makeCreature('leafin',5,species,moves,stable),'わるあがき',species,moves,()=>1,()=>.5);
assert.ok(struggle.damage>0&&struggle.recoil>0);
assert.ok(exhausted.hp<recoilBefore,'Struggle inflicts recoil');
// More faithful turn-based combat: persistent stages within battles, weather,
// passive abilities and cleanup when monsters leave the battlefield.
const buffed=E.makeCreature('flamio',12,species,moves,stable);
const victim=E.makeCreature('leafin',12,species,moves,stable);
const weatherCtx={weather:'clear',weatherTurns:null};
const lv0=E.statsFor(buffed,species.flamio).atk;
assert.equal(E.changeStage(buffed,'atk',2),2);
assert.equal(E.ensureBattleStats(buffed).atk,2);
assert.equal(E.stageFactor(2),2);
assert.equal(E.stageFactor(-2),.5);
assert.equal(E.changeStage(buffed,'atk',20),4,'Stat stages cap at +6');
assert.equal(E.changeStage(buffed,'atk',1),0,'Stage ceiling is enforced');
E.changeStage(buffed,'atk',-20);
assert.equal(E.ensureBattleStats(buffed).atk,-6,'Stat floor is enforced');
const usingBoost=E.calcDamage(E.makeCreature('flamio',12,species,moves,stable),E.makeCreature('leafin',12,species,moves,stable),'いばる',species,{...moves,...E.NEW_MOVES},()=>1,stable,weatherCtx);
assert.equal(usingBoost.stageChange,1);
const highAtk=E.makeCreature('flamio',12,species,moves,stable);
const lowAtk=E.makeCreature('flamio',12,species,moves,stable);
E.changeStage(highAtk,'atk',3);
const dmgTargetA=E.makeCreature('leafin',12,species,moves,stable),dmgTargetB=E.makeCreature('leafin',12,species,moves,stable);
const power0=E.calcDamage(lowAtk,dmgTargetA,'ひっかく',species,moves,()=>1,stable,{weather:'clear'}).damage;
const power1=E.calcDamage(highAtk,dmgTargetB,'ひっかく',species,moves,()=>1,stable,{weather:'clear'}).damage;
assert.ok(power1>power0,'Physical attack stage must change physical damage');
const independent1=E.makeCreature('flamio',25,species,moves,stable);
const independent2=E.makeCreature('flamio',25,species,moves,stable);
const defender1=E.makeCreature('leafin',25,species,moves,stable);
const defender2=E.makeCreature('leafin',25,species,moves,stable);
assert.ok(E.statsFor(independent1,species.flamio).spAtk>0);
assert.ok(E.statsFor(independent1,species.flamio).spDef>0);
assert.ok(independent1.iv.spAtk>=0&&independent1.iv.spAtk<=31);
E.changeStage(independent2,'spAtk',3);
const specialA=E.calcDamage(independent1,defender1,'ひのこ',species,moves,()=>1,stable,{weather:'clear'}).damage;
const specialB=E.calcDamage(independent2,defender2,'ひのこ',species,moves,()=>1,stable,{weather:'clear'}).damage;
assert.ok(specialB>specialA,'Special attack stage must change special damage');
const protected1=E.makeCreature('leafin',25,species,moves,stable);
E.changeStage(protected1,'spDef',3);
const unprotected=E.makeCreature('leafin',25,species,moves,stable);
const spAttackA=E.calcDamage(E.makeCreature('flamio',25,species,moves,stable),protected1,'ひのこ',species,moves,()=>1,stable,{weather:'clear'}).damage;
const spAttackB=E.calcDamage(E.makeCreature('flamio',25,species,moves,stable),unprotected,'ひのこ',species,moves,()=>1,stable,{weather:'clear'}).damage;
assert.ok(spAttackA<spAttackB,'Special defense stage reduces special damage');
const rainy=E.calcDamage(E.makeCreature('flamio',12,species,moves,stable),E.makeCreature('leafin',12,species,moves,stable),'ひのこ',species,moves,()=>1,stable,{weather:'rain'}).damage;
const sunny=E.calcDamage(E.makeCreature('flamio',12,species,moves,stable),E.makeCreature('leafin',12,species,moves,stable),'ひのこ',species,moves,()=>1,stable,{weather:'sun'}).damage;
assert.ok(sunny>rainy,'Fire attack must be stronger under sun');
const rainCast=E.calcDamage(E.makeCreature('flamio',12,species,moves,stable),E.makeCreature('leafin',12,species,moves,stable),'あまごい',species,{...moves,...E.NEW_MOVES},()=>1,stable,weatherCtx);
assert.equal(weatherCtx.weather,'rain');
assert.equal(weatherCtx.weatherTurns,5);
assert.equal(rainCast.weather,'rain');
for(let i=0;i<4;i++)E.tickWeather(weatherCtx);
assert.equal(weatherCtx.weather,'rain');
assert.match(E.tickWeather(weatherCtx),/元に戻った/);
assert.equal(weatherCtx.weather,'clear');
assert.equal(E.weatherFor('lake'),'rain');
assert.equal(E.weatherFor('highland'),'wind');
const sturdy=E.makeCreature('leafin',10,species,moves,stable);
sturdy.ability='がんじょう';
const strong=E.makeCreature('flamio',99,species,moves,stable);
E.calcDamage(strong,sturdy,'ほのおのうず',species,{...moves,...E.NEW_MOVES},()=>1,stable,{weather:'sun'});
assert.equal(sturdy.hp,0,'Fourth-generation Sturdy must NOT block regular lethal damage');
const ohkoTarget=E.makeCreature('leafin',10,species,moves,stable);
ohkoTarget.ability='がんじょう';
const ohkoMoves={...moves,いちげき:{oneHitKO:true,type:'無',p:1,accuracy:100}};
const ohko=E.calcDamage(strong,ohkoTarget,'いちげき',species,ohkoMoves,()=>1,stable,{weather:'clear'});
assert.equal(ohko.damage,0,'Sturdy blocks one-hit KO');
assert.equal(ohkoTarget.hp,ohkoTarget.maxHp);
const normalOHKO=E.makeCreature('leafin',10,species,moves,stable);
E.calcDamage(strong,normalOHKO,'いちげき',species,ohkoMoves,()=>1,stable,{weather:'clear'});
assert.equal(normalOHKO.hp,0,'Non-sturdy monster falls to OHKO');
const swimmer=E.makeCreature('leafin',12,species,moves,stable);swimmer.ability='すいすい';
assert.ok(E.speedFor(swimmer,species,'rain')>E.speedFor(swimmer,species,'clear'));
const windy=E.makeCreature('flamio',12,species,moves,stable);
windy.ability='さいせいりょく';
windy.hp-=12;const lowHP=windy.hp;
E.battleLeave(windy);
assert.ok(windy.hp>lowHP,'Switch-out regenerative ability works');
assert.equal(windy.stages,null);
const storm=E.makeCreature('leafin',12,species,moves,stable);
assert.ok(E.weatherHit(storm,species,'sand')?.damage>0);
const calm=E.makeCreature('flamio',12,species,moves,stable);
assert.equal(E.weatherHit(calm,species,'clear'),null);
// A full four-move set must never auto-lose its oldest move in story battles.
const choiceMon=E.makeCreature('flamio',11,species,moves,stable);
choiceMon.moves=['ひっかく','ひのこ','たいあたり','きあいだめ'];
choiceMon.pp={ひっかく:8,ひのこ:6,たいあたり:5,きあいだめ:3};
const beforeMoves=[...choiceMon.moves];
const deferred=E.gainXP(choiceMon,E.xpNeed(11),species,moves,stable,{chooseMoves:true});
assert.equal(choiceMon.level,12);
assert.deepEqual(choiceMon.moves,beforeMoves,'Full moveset must be preserved until player chooses');
assert.deepEqual(deferred.pending,['ほのおのうず']);
const candidate=E.replaceKnownMove(choiceMon,'ほのおのうず','たいあたり',moves);
assert.equal(candidate.ok,true);
assert(choiceMon.moves.includes('ほのおのうず')&&!choiceMon.moves.includes('たいあたり'));
assert.equal(choiceMon.pp['ほのおのうず'],E.maxPP('ほのおのうず',moves));
assert.equal(E.replaceKnownMove(choiceMon,'ほのおのうず','ひっかく',moves).ok,false,'Cannot learn duplicate moves');
assert.equal(E.replaceKnownMove(choiceMon,'ほのおのうず','missing',moves).ok,false);
console.log('PASS: stat stages, battle accuracy, weather, abilities, evolution, event VM, storage and status effects');
