'use strict';
const assert=require('node:assert/strict');
const R=require('../src/trainer-rematches.js');
const key='forest/森番 レン',base={steps:120,defeated:{},events:{}};
assert.equal(R.status(key,base).unlocked,false);
assert.equal(R.lineup({party:[['leaf',7]],reward:200},key,base),null);
base.defeated[key]=true;
base.events.trainerRematches={[key]:R.markWin(key,base,false)};
assert.equal(R.status(key,base).ready,false);
assert.equal(R.status(key,base).remaining,70);
base.steps+=69;
assert.equal(R.status(key,base).ready,false);
base.steps++;
assert.equal(R.status(key,base).ready,true);
const npc={party:[['chiro',7],['shade',8]],reward:400};
const first=R.lineup(npc,key,base);
assert.deepEqual(first.party,[['chiro',9],['shade',10]]);
assert.equal(first.bonus,2);
assert.equal(first.reward,520);
base.events.trainerRematches[key]=R.markWin(key,base,true);
assert.equal(R.status(key,base).wins,1);
assert.equal(R.status(key,base).ready,false);
base.steps+=70;
const second=R.lineup(npc,key,base);
assert.equal(second.party[0][1],11);
assert(second.reward>first.reward);
let repeated={...base,events:{trainerRematches:{[key]:{wins:15,lastStep:0}}}};
assert.equal(R.lineup(npc,key,repeated).bonus,8,'Level scaling caps');
assert.equal(R.status(key,JSON.parse(JSON.stringify(repeated))).ready,true);
const old={steps:1000,defeated:{[key]:true},events:{}};
assert.equal(R.status(key,old).ready,true,'Old saves offer rematches without migrations');
assert.equal(R.record(key,old).wins,0);
console.log('PASS: opt-in rematches, walking cooldown, escalating levels, rewards and save migration');
