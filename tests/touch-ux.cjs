'use strict';
const assert=require('node:assert/strict');
const U=require('../src/touch-ux.js');
assert.equal(U.layout('submenu',Array(7).fill({})),'list');
assert.equal(U.layout('submenu',Array(3).fill({})),'grid');
assert.equal(U.layout('battleCommands',Array(7).fill({})),'grid');
assert.equal(U.columns('submenu','list'),1);
assert.equal(U.columns('moves','grid'),2);
const options=[{text:'探索',disabled:false},{text:'持ち物',disabled:true},{text:'もどる'}];
assert.equal(U.focusIndex(options,'もどる'),2,'Reopened menu restores chosen control');
assert.equal(U.focusIndex(options,'持ち物'),0,'Disabled saved choice falls back safely');
assert.equal(U.focusIndex([],null),-1);
assert.equal(U.focusIndex([{disabled:true}],'none'),-1);
const rect={left:100,top:20,width:416,height:352};
assert.deepEqual(U.touchTile(100+3.5*32,20+4.5*32,rect,{x:0,y:0}),{x:3,y:4},'Screen position converts to correct tile');
assert.deepEqual(U.touchTile(100+3.5*32,20+4.5*32,rect,{x:64,y:32}),{x:5,y:5},'Scrolled camera is respected');
assert.equal(U.touchTile(40,30,rect,{x:0,y:0}),null,'Outside of canvas does not move');
assert.equal(U.touchTile(300,30,null,{x:0,y:0}),null);
const tiles=Array.from({length:10},()=>Array.from({length:10},()=>1));
tiles[4][3]=4;
const hero={x:4,y:4};
assert.deepEqual(U.tapCommand({x:4,y:4},hero,tiles),{kind:'interact',direction:null});
assert.deepEqual(U.tapCommand({x:5,y:4},hero,tiles,[{x:5,y:4}]),{kind:'interact',direction:'right'},'Tap on adjacent NPC faces and talks');
assert.deepEqual(U.tapCommand({x:3,y:4},hero,tiles),{kind:'interact',direction:'left'},'Blocked tiles cannot be walked into');
assert.deepEqual(U.tapCommand({x:4,y:5},hero,tiles),{kind:'walk',direction:'down'});
assert.deepEqual(U.tapCommand({x:9,y:6},hero,tiles),{kind:'walk',direction:'right'},'Distant tap walks one step, not teleport');
assert.equal(U.tapCommand(null,hero,tiles),null);
assert.equal(U.cancelChoice([{text:'勝負する！'},{text:'まだ待って'}]),1,'B selects explicit cancel instead of battle');
assert.equal(U.cancelChoice([{text:'▶ つづける'}]),0,'B advances a single harmless continuation');
assert.equal(U.cancelChoice([{text:'はい、セーブを消す'},{text:'いいえ'}]),-1,'B never guesses a destructive choice');
assert.equal(U.cancelChoice([{text:'勝負する！'},{text:'受け取る'}]),-1,'Ambiguous dialogues cannot be skipped');
console.log('PASS: touch UX adaptive lists, persisted cursor, canvas coordinate hits and safe B shortcuts');
